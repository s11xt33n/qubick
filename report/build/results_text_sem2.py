DS = {"iris": "Iris", "wine": "Wine", "breast_cancer": "Breast Cancer", "moons": "Moons", "circles": "Circles"}
MODELS = {"mlp": "MLP 32–16", "mlp_matched": "MLP равн. размера", "pl_hybrid": "Hybrid QNN",
          "pl_quantum": "Quantum QNN"}


def f(x, d=3):
    return f"{x:.{d}f}".replace(".", ",")


def pl(ds, model):
    return next(r for r in S["pl"] if r["dataset"] == ds and r["model"] == model)


def test(ds, vs):
    return next(t for t in S["tests"] if t["dataset"] == ds and t["vs"] == vs)


def pv(p):
    return "p < 0,001" if p < 0.001 else f"p = {f(p, 3)}"


def raz(n):
    """«в 21 раз», «в 64 раза»."""
    return "раза" if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14) else "раз"


def arch(k):
    return next(r for r in S["arch"] if r["arch"] == k)


def lr(act, rate):
    return next(r for r in S["lr"] if r["act"] == act and abs(r["lr"] - rate) < 1e-12)


